import {test,expect} from '@playwright/test'
test('login, stored analytics, customer journey and graph',async({page})=>{
  test.skip(!process.env.E2E_PASSWORD,'Set E2E_PASSWORD to the configured local admin password')
  await page.goto('/')
  await page.getByLabel('Password',{exact:true}).fill(process.env.E2E_PASSWORD!)
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Dashboard.'})).toBeVisible()
  await expect(page.getByText('Total customers',{exact:true})).toBeVisible()
  await expect(page.locator('.kpi')).toHaveCount(8)
  await page.setViewportSize({width:1440,height:1000})
  await page.screenshot({path:'../docs/dashboard-desktop.jpg',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await expect(page.getByRole('button',{name:'Open navigation'})).toBeVisible()
  await page.screenshot({path:'../docs/dashboard-mobile.jpg',fullPage:true})
  await page.setViewportSize({width:1440,height:1000})
  await page.getByRole('button',{name:'Customer Management'}).click()
  await expect(page.getByRole('cell',{name:'Demo Customer 001'})).toBeVisible()
  await page.getByRole('cell',{name:'Demo Customer 001'}).click()
  await expect(page.getByRole('heading',{name:'Demo Customer 001'})).toBeVisible()
  await page.getByRole('button',{name:'Temporal Knowledge Graph'}).click()
  await expect(page.locator('.react-flow')).toBeVisible()
  await page.getByLabel('Valid at (local time)',{exact:true}).fill('2025-01-01T00:00')
  await page.getByRole('button',{name:'Apply time filters',exact:true}).click()
  await expect(page.getByText('No relationships match both time filters.')).toBeVisible()
})

test('CSV customer import, JSON events, grounded answer and downloadable report',async({page})=>{
  test.skip(!process.env.E2E_PASSWORD,'Set E2E_PASSWORD to the configured local admin password')
  const id='PW-'+Date.now()
  await page.goto('/')
  await page.getByLabel('Password',{exact:true}).fill(process.env.E2E_PASSWORD!)
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await page.getByRole('button',{name:'Import data',exact:true}).click()
  await page.getByRole('combobox').selectOption('customers')
  await page.getByRole('checkbox',{name:'This file contains synthetic demonstration data'}).check()
  await page.getByLabel('Select dataset').setInputFiles({name:'playwright-customers.csv',mimeType:'text/csv',buffer:Buffer.from(`id,name\n${id},Playwright Synthetic Customer\n`)})
  await page.getByRole('button',{name:'Validate & preview',exact:true}).click()
  await page.getByRole('button',{name:'Import validated data',exact:true}).click()
  await expect(page.locator('tbody').getByText('playwright-customers.csv',{exact:true})).toBeVisible()
  await page.getByRole('combobox').selectOption('events')
  const events=['website_visit','product_view','add_to_cart','purchase'].map((event_type,i)=>({event_id:`${id}-E${i}`,customer_id:id,event_type,entity_id:'P001',channel:'website',event_time:`2026-11-01T10:0${i}:00Z`,properties:{amount:event_type==='purchase'?149:0,synthetic:true}}))
  await page.getByLabel('Select dataset').setInputFiles({name:'playwright-events.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(events))})
  await page.getByRole('button',{name:'Validate & preview',exact:true}).click()
  await page.getByRole('button',{name:'Import validated data',exact:true}).click()
  await expect(page.locator('tbody').getByText('playwright-events.json',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Journey Analytics',exact:true}).click()
  await page.getByLabel('Customer ID',{exact:true}).fill(id)
  await page.getByRole('button',{name:'Explore journey',exact:true}).click()
  await expect(page.locator('.timeline')).toContainText(`${id}-E3`)
  await page.getByRole('button',{name:'AI Insights',exact:true}).click()
  await page.getByRole('button',{name:'Analyze evidence',exact:true}).click()
  await expect(page.getByText('local-evidence-summary',{exact:true})).toBeVisible()
  await expect(page.locator('.answer')).toContainText('observed channel conversion')
  await page.getByRole('button',{name:'Reports',exact:true}).click()
  await page.getByRole('button',{name:'Generate report',exact:true}).click()
  await expect(page.locator('tbody tr').first()).toContainText('Analytics Reports')
  const downloadEvent=page.waitForEvent('download')
  await page.getByRole('button',{name:'JSON',exact:true}).first().click()
  const download=await downloadEvent
  expect(download.suggestedFilename()).toMatch(/journeygraph-.*\.json/)
})
